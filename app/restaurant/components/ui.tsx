// Modal dialog component with blur backdrop and responsive sizing
export function Modal({
  isOpen,
  onClose,
  title,
  children,
  maxWidth = "480px"
}: {
  isOpen: boolean;
  onClose: () => void;
  title: string;
  children: React.ReactNode;
  maxWidth?: string;
}) {
  React.useEffect(() => {
    if (isOpen) {
      document.body.style.overflow = 'hidden';
    } else {
      document.body.style.overflow = '';
    }
    return () => {
      document.body.style.overflow = '';
    };
  }, [isOpen]);

  if (!isOpen) return null;

  return (
    <div
      style={{
        position: 'fixed',
        top: 0,
        left: 0,
        right: 0,
        bottom: 0,
        backgroundColor: 'rgba(0, 0, 0, 0.45)',
        backdropFilter: 'blur(5px)',
        zIndex: 1000,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        padding: '16px',
      }}
      onClick={onClose}
    >
      <div
        style={{
          width: '100%',
          maxWidth,
          backgroundColor: 'var(--bg-elev)',
          borderRadius: 'var(--radius)',
          boxShadow: 'var(--shadow-lg)',
          border: '1px solid var(--border)',
          overflow: 'hidden',
          display: 'flex',
          flexDirection: 'column',
          maxHeight: '90vh',
          animation: 'fadeIn 0.2s ease-out',
        }}
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div
          style={{
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            padding: '16px 20px',
            borderBottom: '1px solid var(--border)',
            background: 'var(--bg-muted)',
          }}
        >
          <h3 style={{ margin: 0, color: 'var(--fg)', fontSize: '16px', fontWeight: 600 }}>{title}</h3>
          <button
            onClick={onClose}
            style={{
              background: 'transparent',
              border: 'none',
              cursor: 'pointer',
              color: 'var(--muted)',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              padding: '4px',
              borderRadius: '4px',
            }}
          >
            <Icon name="x" size={20} />
          </button>
        </div>

        {/* Modal Body */}
        <div style={{ padding: '20px', overflowY: 'auto', flex: 1 }}>
          {children}
        </div>
      </div>
    </div>
  );
}

// Toast Alert Component
export function Toast({
  message,
  type = "info",
  onClose
}: {
  message: string;
  type?: "info" | "success" | "warning" | "error";
  onClose: () => void;
}) {
  React.useEffect(() => {
    const timer = setTimeout(onClose, 2800);
    return () => clearTimeout(timer);
  }, [onClose]);

  const colors = {
    info: { border: "var(--border-strong)", bg: "var(--bg-elev)", text: "var(--fg)" },
    success: { border: "#2a9d8f", bg: "rgba(42, 157, 143, 0.05)", text: "#2a9d8f" },
    warning: { border: "#f4a261", bg: "rgba(244, 162, 97, 0.05)", text: "#f4a261" },
    error: { border: "#e76f51", bg: "rgba(231, 111, 81, 0.05)", text: "#e76f51" }
  };

  const scheme = colors[type];

  return (
    <div
      style={{
        position: 'fixed',
        bottom: '80px',
        left: '50%',
        transform: 'translateX(-50%)',
        zIndex: 9999,
        background: 'var(--bg-elev)',
        color: scheme.text,
        border: `1.5px solid ${scheme.border}`,
        padding: '12px 18px',
        borderRadius: 'var(--radius-sm)',
        boxShadow: 'var(--shadow-lg)',
        display: 'flex',
        alignItems: 'center',
        gap: '8px',
        maxWidth: '90%',
        fontSize: '13px',
        fontWeight: 600,
        pointerEvents: 'auto',
        animation: 'slideUp 0.3s cubic-bezier(0.18, 0.89, 0.32, 1.28)',
      }}
    >
      <Icon name={type === "success" ? "check" : type === "error" ? "x" : "info"} size={16} />
      <span>{message}</span>
      <style>{`
        @keyframes slideUp {
          from { transform: translate(-50%, 20px); opacity: 0; }
          to { transform: translate(-50%, 0); opacity: 1; }
        }
      `}</style>
    </div>
  );
}
